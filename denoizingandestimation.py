plt.show()

"""# **Analisis en frecuencia**"""

# Calculo del espectro de la senial
# Mean_k = np.fft.fft(x_np)
Means_k = FFT.fft(means, 128)
MeanFilt_k = FFT.fft([1/window_size]*window_size, 128)
X_ma_k = FFT.fft(x_ma, 128)

Means_k_mag = np.abs(Means_k)
MeanFilt_k_mag = np.abs(MeanFilt_k)
X_ma_k_mag = np.abs(X_ma_k)
#X_np_mag = np.abs(X_np)
#X_np_phase = np.angle(X_np)

plt.subplot(3,1,1)
plt.title('Espectro de los datos')
plt.plot(Means_k_mag[0:(128>>1) - 2])
#plt.plot(np.log(X_ma_k_mag[0:(128>>1) - 2]))

plt.subplot(3,1,2)
plt.plot(MeanFilt_k_mag[0:(128>>1) - 2])

plt.subplot(3,1,3)
plt.plot(X_ma_k_mag[0:(128>>1) - 2])
#plt.plot(np.log(X_ma_k_mag[0:(128>>1) - 2]))

plt.show()

"""# **Regresion lineal**"""

day_samps = [n for n in range(window_size-1,len(days))]
#day_samps = [n for n in range(len(days))]

res = stats.linregress(day_samps,x_ma[window_size - 1:])
#res = stats.linregress(day_samps,x_ma)

print('T = ',res.slope,"n +",res.intercept)

x_est = [res.slope*day +  res.intercept for day in day_samps]

plt.plot(day_samps, means[window_size - 1:],'*',label='Datos Originales')
plt.plot(day_samps, x_ma[window_size - 1:], 'o', label='Datos Filtrados')
#plt.plot(day_samps, x_ma, 'o', label='Datos Filtrados')
plt.plot(day_samps, x_est, 'r', label='Estimacion')
plt.xlabel('n (Día)')
plt.ylabel('Temperatura [C]')
plt.title('Temperatura media en CDMX')
plt.grid('both')
ax = plt.gca()
