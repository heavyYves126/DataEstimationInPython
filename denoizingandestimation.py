import pandas as pd
import matplotlib.pyplot as plt
import scipy.signal as sig
import scipy.fft as FFT
import scipy.stats as stats
import numpy as np

"""#**Carga de datos**"""

dataF = pd.read_csv('TemperaCDMXEnero.csv')
#dataArr = dataF.to_string()
#print(dataArr)
print(dataF.info())

days = list(dataF['Día'])
means = list(dataF['Temperatura media [C]'])

#for day,meanTemp in zip(days,meanTemps):
#  print(day,'\t',meanTemp)

#plt.plot(days,means)
#plt.show()

"""#**Concatenacion de datos**"""

monthlyTemp = ['TemperaCDMXEnero.csv','TemperaCDMXFebrero.csv','TemperaCDMXMarzo.csv','TemperaCDMXAbril.csv']

days = []
means = []

for month in monthlyTemp:
  dataF = pd.read_csv(month)
  #print(dataF.info())
  days += list(dataF['Día'])
  means += list(dataF['Temperatura media [C]'])

"""Visualización de datos"""

print(plt.style.available)
plt.style.use('ggplot')

plt.plot(means)
plt.xlabel('Día')
plt.ylabel('Temperatura [C]')
plt.title('Temperatura media en CDMX')
plt.grid('both')
plt.show()

"""# Filtrado de datos"""

window_size = 12
x_ma = sig.lfilter([1/window_size]*window_size,[1],means)
#y = sig.convolve(means,[1/M]*M)

plt.plot(x_ma[window_size - 1:])
#plt.plot(y)
ax = plt.gca()
ax.set_xlim([0, 120])
ax.set_ylim([10, 23])
plt.xlabel('Día')
plt.ylabel('Temperatura [C]')
plt.title('Temperatura media en CDMX')
plt.grid('both')
plt.show()

#print(y)

numbers_series = pd.Series(means)
windows = numbers_series.rolling(window_size)

# Create a series of moving
# averages of each window
moving_averages = windows.mean()

# Convert pandas series back to list
moving_averages_list = moving_averages.tolist()

# Remove null entries from the list
final_list = moving_averages_list[window_size - 1:]

#print(final_list)
plt.plot(final_list)
ax = plt.gca()
ax.set_xlim([0, 120])
ax.set_ylim([10, 23])
plt.show()

plt.subplot(2,1,1)
plt.plot(means)
